//! Rust backend for emitting hand-written-style recursive-descent parsers.

use rdgen_ir::{Element, Grammar, RecoveryStrategy, Rule};

/// Emit the typed AST declarations for a resolved grammar.
///
/// Parser-method emission is intentionally separate: the AST declaration
/// contract must remain usable by every parser backend and can be tested
/// independently of parsing control flow.
pub fn emit_ast(grammar: &Grammar) -> Result<String, String> {
    let mut output = String::from("// Generated by rdgen; do not edit.\n\n");
    output.push_str("#[derive(Clone, Debug, PartialEq)]\n");
    output.push_str("pub struct Token(pub String);\n\n");
    for rule in &grammar.rules {
        validate_labeled_groups(&rule.alternatives.iter().flat_map(|alternative| alternative.elements.iter()).collect::<Vec<_>>())?;
        emit_rule(
            &mut output,
            rule,
            grammar
                .precedence
                .iter()
                .filter(|table| table.rule == rule.name)
                .collect(),
        )?;
    }
    Ok(output)
}

fn validate_labeled_groups(elements: &[&Element]) -> Result<(), String> {
    for element in elements {
        match element {
            Element::Group {
                label: Some(label),
                alternatives,
                ..
            } if alternatives.len() > 1 => {
                return Err(format!(
                    "Rust emitter does not yet support labeled group '{}' with alternatives",
                    label
                ));
            }
            Element::Group { alternatives, .. } => {
                for alternative in alternatives {
                    validate_labeled_groups(&alternative.iter().collect::<Vec<_>>())?;
                }
            }
            Element::Repeat { element, .. } => {
                validate_labeled_groups(&[element.as_ref()])?;
            }
            _ => {}
        }
    }
    Ok(())
}

fn emit_rule(
    output: &mut String,
    rule: &Rule,
    precedence: Vec<&rdgen_ir::PrecedenceTable>,
) -> Result<(), String> {
    let enum_name = type_name(&rule.name);
    output.push_str("#[derive(Clone, Debug, PartialEq)]\n");
    output.push_str(&format!("pub enum {} {{\n", enum_name));
    let mut variants = std::collections::HashSet::new();
    for (index, alternative) in rule.alternatives.iter().enumerate() {
        let variant = variant_name(rule, alternative, index);
        if !variants.insert(variant.clone()) {
            return Err(format!(
                "duplicate AST variant '{}' in rule '{}'",
                variant, rule.name
            ));
        }
        output.push_str("    ");
        output.push_str(&variant);
        if alternative.constructor.fields.is_empty() {
            output.push_str(",\n");
            continue;
        }
        output.push_str(" {\n");
        let mut field_names = std::collections::HashSet::new();
        for field in &alternative.constructor.fields {
            let element = find_labeled_element(&alternative.elements, &field.source_label)
                .ok_or_else(|| {
                    format!(
                        "missing label '{}' in rule '{}'",
                        field.source_label, rule.name
                    )
                })?;
            let generated_name = field_name(&field.field);
            if !field_names.insert(generated_name.clone()) {
                return Err(format!(
                    "constructor fields '{}' collide after Rust escaping in rule '{}'",
                    field.field, rule.name
                ));
            }
            output.push_str(&format!("        {}: {},\n", generated_name, rust_type(element)));
        }
        output.push_str("    },\n");
    }
    for table in precedence {
        for level in &table.levels {
            let Some(constructor) = &level.constructor else {
                continue;
            };
            let variant = type_name(&constructor.type_name.0);
            if !variants.insert(variant.clone()) {
                return Err(format!(
                    "duplicate AST variant '{}' in rule '{}', including precedence constructors",
                    variant, rule.name
                ));
            }
            output.push_str(&format!("    {} {{\n", variant));
            let mut field_names = std::collections::HashSet::new();
            for field in &constructor.fields {
                let generated_name = field_name(&field.field);
                if !field_names.insert(generated_name.clone()) {
                    return Err(format!(
                        "precedence constructor fields '{}' collide after Rust escaping in rule '{}'",
                        field.field, rule.name
                    ));
                }
                let field_type = match field.source_label.as_str() {
                    "left" | "right" => format!("Box<{}>", type_name(&rule.name)),
                    "operator" => "Token".to_owned(),
                    _ => unreachable!("precedence constructor validation guarantees roles"),
                };
                output.push_str(&format!(
                    "        {}: {},\n",
                    generated_name, field_type
                ));
            }
            output.push_str("    },\n");
        }
    }
    output.push_str("}\n\n");
    Ok(())
}

fn variant_name(rule: &Rule, alternative: &rdgen_ir::Alternative, index: usize) -> String {
    if alternative.constructor.fields.is_empty() && alternative.constructor.type_name.0 == rule.name
    {
        format!("Alt{}", index + 1)
    } else {
        type_name(&alternative.constructor.type_name.0)
    }
}

fn find_labeled_element<'a>(elements: &'a [Element], label: &str) -> Option<&'a Element> {
    for element in elements {
        match element {
            Element::Rule {
                label: Some(name), ..
            }
            | Element::Token {
                label: Some(name), ..
            }
            | Element::Literal {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Group {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Repeat {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Group { alternatives, .. } => {
                for alternative in alternatives {
                    if let Some(found) = find_labeled_element(alternative, label) {
                        return Some(found);
                    }
                }
            }
            Element::Repeat { element, .. } => {
                if let Some(found) =
                    find_labeled_element(std::slice::from_ref(element.as_ref()), label)
                {
                    return Some(found);
                }
            }
            _ => {}
        }
    }
    None
}

fn rust_type(element: &Element) -> String {
    match element {
        Element::Rule { rule, .. } => format!("Box<{}>", type_name(rule)),
        Element::Token { .. } | Element::Literal { .. } => "Token".into(),
        Element::Repeat {
            element,
            max: Some(1),
            ..
        } => format!("Option<{}>", rust_type(rust_repeat_child(element))),
        Element::Repeat { element, .. } => {
            format!("Vec<{}>", rust_type(rust_repeat_child(element)))
        }
        Element::Group { alternatives, .. } if alternatives.len() == 1 => {
            rust_group_type(&alternatives[0])
        }
        Element::Group { .. } => "()".into(),
    }
}

fn rust_group_type(elements: &[Element]) -> String {
    match elements {
        [] => "()".into(),
        [element] => rust_type(element),
        elements => format!(
            "({})",
            elements
                .iter()
                .map(rust_type)
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn rust_repeat_child(element: &Element) -> &Element {
    match element {
        Element::Group { alternatives, .. }
            if alternatives.len() == 1 && alternatives[0].len() == 1 =>
        {
            &alternatives[0][0]
        }
        _ => element,
    }
}

fn type_name(name: &str) -> String {
    let mut result = String::new();
    for part in name.split('_') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            result.extend(first.to_uppercase());
        }
        result.extend(chars);
    }
    if result.is_empty() {
        "Anonymous".into()
    } else {
        result
    }
}

fn field_name(name: &str) -> String {
    match name {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern"
        | "false" | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match"
        | "mod" | "move" | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static"
        | "struct" | "super" | "trait" | "true" | "type" | "unsafe" | "use" | "where"
        | "while" | "async" | "await" | "dyn" | "abstract" | "become" | "box" | "do"
        | "final" | "macro" | "override" | "priv" | "typeof" | "unsized" | "virtual"
        | "yield" | "try" => {
            format!("r#{}", name)
        }
        _ => name.to_owned(),
    }
}

/// Emit a Rust parser from the resolved grammar IR.
pub fn emit(grammar: &Grammar) -> Result<String, String> {
    let mut output = emit_ast(grammar)?;
    emit_precedence_metadata(&mut output, grammar)?;
    output.push_str(&emit_parser(grammar)?);
    Ok(output)
}

fn emit_precedence_metadata(output: &mut String, grammar: &Grammar) -> Result<(), String> {
    if grammar.precedence.is_empty() {
        return Ok(());
    }
    if grammar
        .rules
        .iter()
        .any(|rule| type_name(&rule.name) == "RdgenPrecedenceLevel")
    {
        return Err(
            "Rust grammar rule name collides with generated type 'RdgenPrecedenceLevel'"
                .to_owned(),
        );
    }
    output.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\n");
    output.push_str(
        "pub struct RdgenPrecedenceField { pub field: &'static str, pub source_label: &'static str }\n\n",
    );
    output.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\n");
    output.push_str(
        "pub struct RdgenPrecedenceLevel { pub operators: &'static [&'static str], pub right_associative: bool, pub left_binding_power: usize, pub right_binding_power: usize, pub constructor_type: Option<&'static str>, pub constructor_fields: &'static [RdgenPrecedenceField] }\n\n",
    );
    let mut constants = std::collections::HashSet::new();
    for table in &grammar.precedence {
        let constant = format!("{}_PRECEDENCE", constant_name(&table.rule));
        if !constants.insert(constant.clone()) {
            return Err(format!(
                "duplicate generated precedence constant '{}'",
                constant
            ));
        }
        output.push_str(&format!(
            "pub const {}: &[RdgenPrecedenceLevel] = &[\n",
            constant
        ));
        for level in &table.levels {
            let operators = level
                .operators
                .iter()
                .map(|operator| format!("{:?}", operator))
                .collect::<Vec<_>>()
                .join(", ");
            let (left_binding_power, right_binding_power) = table
                .binding_powers(&level.operators[0])
                .expect("precedence validation guarantees a declared operator");
            let constructor_type = level
                .constructor
                .as_ref()
                .map(|constructor| constructor.type_name.0.as_str());
            let constructor_fields = level
                .constructor
                .as_ref()
                .map(|constructor| {
                    constructor
                        .fields
                        .iter()
                        .map(|field| {
                            format!(
                                "RdgenPrecedenceField {{ field: {:?}, source_label: {:?} }}",
                                field.field, field.source_label
                            )
                        })
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .filter(|fields| !fields.is_empty())
                .map_or_else(|| "&[]".to_owned(), |fields| format!("&[{}]", fields));
            output.push_str(&format!(
                "    RdgenPrecedenceLevel {{ operators: &[{}], right_associative: {}, left_binding_power: {}, right_binding_power: {}, constructor_type: {:?}, constructor_fields: {} }},\n",
                operators,
                matches!(level.associativity, rdgen_ir::Associativity::Right),
                left_binding_power,
                right_binding_power,
                constructor_type,
                constructor_fields
            ));
        }
        output.push_str("];\n");
        output.push_str(&format!(
            "pub fn {}_precedence(operator: &str) -> Option<(usize, bool)> {{ {}.iter().enumerate().find_map(|(level, spec)| spec.operators.iter().any(|candidate| *candidate == operator).then_some((level, spec.right_associative))) }}\n\n",
            table.rule, constant
        ));
        output.push_str(&format!(
            "pub fn {}_binding_power(operator: &str) -> Option<(usize, usize)> {{ {}_PRECEDENCE.iter().find_map(|spec| spec.operators.iter().any(|candidate| *candidate == operator).then_some((spec.left_binding_power, spec.right_binding_power))) }}\n\n",
            table.rule, constant_name(&table.rule)
        ));
    }
    Ok(())
}

fn constant_name(name: &str) -> String {
    name.chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

/// Emit parser control flow for the currently supported core element set.
pub fn emit_parser(grammar: &Grammar) -> Result<String, String> {
    for rule in &grammar.rules {
        for alternative in &rule.alternatives {
            if let Some(recovery) = &alternative.recovery {
                if !matches!(recovery.strategy, RecoveryStrategy::SkipUntilSync) {
                    return Err(format!(
                        "Rust parser emitter does not yet support {:?} recovery in rule '{}'",
                        recovery.strategy, rule.name
                    ));
                }
            }
        }
    }
    let start = grammar
        .rules
        .iter()
        .find(|rule| rule.name == grammar.start)
        .ok_or_else(|| format!("start rule '{}' is not declared", grammar.start))?;
    let mut output = String::from(
        "#[derive(Clone, Debug, PartialEq)]\n"
            .to_owned() + "pub struct ParseError { pub message: String, pub position: usize }\n\n"
            + "pub type TerminalScanner = fn(&str, usize, &str) -> Option<(Token, usize)>;\n\n"
            + "fn missing_terminal(_: &str, _: usize, _: &str) -> Option<(Token, usize)> { None }\n\n"
            + "pub type TriviaSkipper = fn(&str, usize) -> usize;\n\n"
            + "fn skip_no_trivia(_: &str, position: usize) -> usize { position }\n\n"
            + "pub type LiteralMatcher = fn(&str, usize, &str) -> Option<usize>;\n\n"
            + "fn match_literal(source: &str, position: usize, literal: &str) -> Option<usize> { source.get(position..)?.starts_with(literal).then_some(position + literal.len()) }\n\n"
            + "#[allow(dead_code)]\n"
            + "pub struct Parser<'a> { source: &'a str, position: usize, scan_terminal: TerminalScanner, skip_trivia: TriviaSkipper, match_literal: LiteralMatcher, best_error: Option<ParseError>, lexical_mode: bool }\n\n"
            + "#[allow(dead_code)]\n"
            + "impl<'a> Parser<'a> {\n"
            + "    pub fn new(source: &'a str) -> Self { Self::with_terminal_scanner(source, missing_terminal) }\n"
            + "    pub fn with_terminal_scanner(source: &'a str, scan_terminal: TerminalScanner) -> Self { Self::with_scanner_and_trivia(source, scan_terminal, skip_no_trivia) }\n"
            + "    pub fn with_scanner_and_trivia(source: &'a str, scan_terminal: TerminalScanner, skip_trivia: TriviaSkipper) -> Self { Self::with_lexical_config(source, scan_terminal, skip_trivia, match_literal) }\n"
            + "    pub fn with_lexical_config(source: &'a str, scan_terminal: TerminalScanner, skip_trivia: TriviaSkipper, match_literal: LiteralMatcher) -> Self { Self { source, position: 0, scan_terminal, skip_trivia, match_literal, best_error: None, lexical_mode: false } }\n"
            + "    pub fn parse(&mut self) -> Result<" + &type_name(&start.name) + ", ParseError> { let value = match self.parse_" + &start.name + "() { Ok(value) => value, Err(error) => return Err(self.best_error.take().unwrap_or(error)) }; self.skip_trivia(); if self.position != self.source.len() { let error = ParseError { message: \"unexpected trailing input\".into(), position: self.position }; self.remember_error(&error); return Err(self.best_error.take().unwrap_or(error)); } Ok(value) }\n"
            + "    fn remember_error(&mut self, error: &ParseError) { if self.best_error.as_ref().map_or(true, |best| error.position >= best.position) { self.best_error = Some(error.clone()); } }\n"
            + "    fn skip_trivia(&mut self) { if self.lexical_mode { return; } let next = (self.skip_trivia)(self.source, self.position); if next >= self.position && next <= self.source.len() && self.source.is_char_boundary(next) { self.position = next; } }\n"
            + "    fn matches_terminator(&mut self, literal: &str) -> bool { let start = self.position; let mut first = true; for part in literal.split_whitespace() { if !first { self.skip_trivia(); } let Some(end) = (self.match_literal)(self.source, self.position, part) else { self.position = start; return false; }; self.position = end; first = false; } self.position = start; true }\n"
            + "    fn skip_until_sync(&mut self, sync: &[&str]) { while self.position < self.source.len() { if sync.iter().any(|literal| self.source[self.position..].starts_with(literal)) { return; } if let Some(character) = self.source[self.position..].chars().next() { self.position += character.len_utf8(); } else { return; } } }\n"
            + "    fn expect_literal(&mut self, literal: &str) -> Result<Token, ParseError> {\n"
            + "        self.skip_trivia();\n"
            + "        if self.position <= self.source.len() && self.source.is_char_boundary(self.position) {\n"
            + "            if let Some(end) = (self.match_literal)(self.source, self.position, literal) {\n"
            + "                if end >= self.position && end <= self.source.len() && self.source.is_char_boundary(end) { self.position = end; return Ok(Token(literal.to_owned())); }\n"
            + "            }\n"
            + "        }\n"
            + "        let error = ParseError { message: format!(\"expected {:?}\", literal), position: self.position }; self.remember_error(&error); Err(error)\n"
            + "    }\n"
            + "    fn expect_terminal(&mut self, name: &str) -> Result<Token, ParseError> {\n"
            + "        self.skip_trivia();\n"
            + "        match (self.scan_terminal)(self.source, self.position, name) {\n"
            + "            Some((token, end)) if end > self.position && end <= self.source.len() && self.source.is_char_boundary(self.position) && self.source.is_char_boundary(end) => { self.position = end; Ok(token) }\n"
            + "            _ => { let error = ParseError { message: format!(\"expected terminal {:?}\", name), position: self.position }; self.remember_error(&error); Err(error) },\n"
            + "        }\n"
            + "    }\n",
    );
    output.push_str(
        "    pub fn parse_precedence_climbing<T>(\n        &mut self,\n        minimum_binding_power: usize,\n        parse_atom: fn(&mut Self) -> Result<T, ParseError>,\n        parse_operator: fn(&mut Self) -> Result<Option<(Token, usize, usize)>, ParseError>,\n        combine: fn(T, Token, T) -> T,\n    ) -> Result<T, ParseError> {\n        let mut left = match parse_atom(self) {\n            Ok(value) => value,\n            Err(error) => { self.remember_error(&error); return Err(error); }\n        };\n        loop {\n            let operator_start = self.position;\n            let parsed_operator = match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            };\n            let Some((operator, left_binding_power, right_binding_power)) = parsed_operator else {\n                self.position = operator_start;\n                break;\n            };\n            if left_binding_power < minimum_binding_power {\n                self.position = operator_start;\n                break;\n            }\n            let right = match self.parse_precedence_climbing(right_binding_power, parse_atom, parse_operator, combine) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            };\n            left = combine(left, operator, right);\n        }\n        Ok(left)\n    }\n\n",
    );
    output.push_str(
        "    pub fn parse_precedence_climbing_tokens<T>(\n        &mut self,\n        minimum_binding_power: usize,\n        parse_atom: fn(&mut Self) -> Result<T, ParseError>,\n        parse_operator: fn(&mut Self) -> Result<Option<Token>, ParseError>,\n        binding_power: fn(&str) -> Option<(usize, usize)>,\n        combine: fn(T, Token, T) -> T,\n    ) -> Result<T, ParseError> {\n        let mut left = match parse_atom(self) {\n            Ok(value) => value,\n            Err(error) => { self.remember_error(&error); return Err(error); }\n        };\n        loop {\n            let operator_start = self.position;\n            let Some(operator) = match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            } else {\n                self.position = operator_start;\n                break;\n            };\n            let Some((left_binding_power, right_binding_power)) = binding_power(&operator.0) else {\n                let error = ParseError { message: format!(\"unknown precedence operator {:?}\", operator.0), position: operator_start };\n                self.remember_error(&error);\n                return Err(error);\n            };\n            if left_binding_power < minimum_binding_power {\n                self.position = operator_start;\n                break;\n            }\n            let right = match self.parse_precedence_climbing_tokens(right_binding_power, parse_atom, parse_operator, binding_power, combine) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            };\n            left = combine(left, operator, right);\n        }\n        Ok(left)\n    }\n\n",
    );
    for table in &grammar.precedence {
        if grammar
            .rules
            .iter()
            .any(|rule| rule.name == format!("{}_precedence", table.rule))
        {
            return Err(format!(
                "Rust precedence wrapper for rule '{}' collides with grammar rule '{}_precedence'",
                table.rule, table.rule
            ));
        }
        output.push_str(&format!(
            "    pub fn parse_{}_precedence<T>(&mut self, minimum_binding_power: usize, parse_atom: fn(&mut Self) -> Result<T, ParseError>, parse_operator: fn(&mut Self) -> Result<Option<Token>, ParseError>, combine: fn(T, Token, T) -> T) -> Result<T, ParseError> {{ self.parse_precedence_climbing_tokens(minimum_binding_power, parse_atom, parse_operator, {}_binding_power, combine) }}\n\n",
            table.rule, table.rule
        ));
        if table.levels.iter().all(|level| level.constructor.is_some()) {
            emit_precedence_ast_helper(&mut output, table)?;
        }
    }
    for rule in &grammar.rules {
        emit_parser_rule(&mut output, rule)?;
    }
    output = output.replace(
        "let Some(operator) = match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            } else {",
        "let Some(operator) = (match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            }) else {",
    );
    output.push_str("}\n");
    Ok(output)
}

fn emit_precedence_ast_helper(
    output: &mut String,
    table: &rdgen_ir::PrecedenceTable,
) -> Result<(), String> {
    let rule_type = type_name(&table.rule);
    let combine_name = format!("{}_precedence_combine", table.rule);
    output.push_str(&format!(
        "    fn {}(left: {}, operator: Token, right: {}) -> {} {{\n",
        combine_name, rule_type, rule_type, rule_type
    ));
    output.push_str("        match operator.0.as_str() {\n");
    for level in &table.levels {
        let constructor = level
            .constructor
            .as_ref()
            .expect("precedence AST helper requires constructors for every level");
        let variant = type_name(&constructor.type_name.0);
        for operator in &level.operators {
            output.push_str(&format!("            {:?} => {}::{} {{\n", operator, rule_type, variant));
            for field in &constructor.fields {
                let value = match field.source_label.as_str() {
                    "left" => "Box::new(left)".to_owned(),
                    "operator" => "operator".to_owned(),
                    "right" => "Box::new(right)".to_owned(),
                    _ => unreachable!("precedence constructor validation guarantees roles"),
                };
                output.push_str(&format!(
                    "                {}: {},\n",
                    field_name(&field.field),
                    value
                ));
            }
            output.push_str("            },\n");
        }
    }
    output.push_str("            other => unreachable!(\"unknown precedence operator {:?}\", other),\n");
    output.push_str("        }\n    }\n\n");
    output.push_str(&format!(
        "    pub fn parse_{}_precedence_ast(&mut self, minimum_binding_power: usize, parse_atom: fn(&mut Self) -> Result<{}, ParseError>, parse_operator: fn(&mut Self) -> Result<Option<Token>, ParseError>) -> Result<{}, ParseError> {{ self.parse_precedence_climbing_tokens(minimum_binding_power, parse_atom, parse_operator, {}_binding_power, {}) }}\n\n",
        table.rule, rule_type, rule_type, table.rule, format!("Self::{}", combine_name)
    ));
    Ok(())
}

fn emit_parser_rule(output: &mut String, rule: &Rule) -> Result<(), String> {
    output.push_str(&format!(
        "    fn parse_{}(&mut self) -> Result<{}, ParseError> {{\n",
        rule.name,
        type_name(&rule.name)
    ));
    if rule.lexical {
        output.push_str("        let lexical_start = self.position;\n        self.skip_trivia();\n        let previous_lexical_mode = self.lexical_mode;\n        self.lexical_mode = true;\n");
    }
    for (index, alternative) in rule.alternatives.iter().enumerate() {
        if !rule.lexical {
            output.push_str("        let start = self.position;\n");
        }
        output.push_str(&format!(
            "        let attempt: Result<{}, ParseError> = (|| {{\n",
            type_name(&rule.name)
        ));
        for (index, element) in alternative.elements.iter().enumerate() {
            let variable = element_variable(element, index);
            emit_element_binding(output, element, &variable, "            ")?;
        }
        output.push_str(&format!(
            "            Ok({}::{}{})\n",
            type_name(&rule.name),
            variant_name(rule, alternative, index),
            emit_constructor_fields(alternative)?
        ));
        output.push_str("        })();\n");
        if rule.lexical {
            output.push_str("        match attempt { Ok(value) => { self.lexical_mode = previous_lexical_mode; return Ok(value); }, Err(_) => self.position = lexical_start }\n");
        } else {
            output.push_str("        match attempt { Ok(value) => return Ok(value), Err(_) => self.position = start }\n");
        }
    }
    if rule.lexical {
        output.push_str("        self.lexical_mode = previous_lexical_mode;\n        self.position = lexical_start;\n");
    }
    if let Some(recovery) = rule.alternatives.iter().find_map(|alternative| {
        (alternative
            .recovery
            .as_ref()
            .is_some_and(|point| matches!(point.strategy, RecoveryStrategy::SkipUntilSync)))
        .then(|| {
            alternative
                .recovery
                .as_ref()
                .expect("recovery point checked")
        })
    }) {
        let sync = recovery
            .sync_tokens
            .iter()
            .map(|token| format!("{:?}", token))
            .collect::<Vec<_>>()
            .join(", ");
        output.push_str(&format!("        self.skip_until_sync(&[{}]);\n", sync));
    }
    output.push_str(&format!("        let error = ParseError {{ message: \"no alternative for {}\".into(), position: self.position }}; self.remember_error(&error); Err(error)\n", rule.name));
    output.push_str("    }\n");
    Ok(())
}

fn emit_element_parse(element: &Element) -> Result<String, String> {
    match element {
        Element::Literal { value, .. } => Ok(format!("self.expect_literal({:?})?", value)),
        Element::Token { token, .. } => Ok(format!("self.expect_terminal({:?})?", token)),
        Element::Rule { rule, .. } => Ok(format!("Box::new(self.parse_{}()?)", rule)),
        Element::Group { .. } | Element::Repeat { .. } => emit_element_expression(element),
    }
}

fn emit_element_binding(
    output: &mut String,
    element: &Element,
    variable: &str,
    indent: &str,
) -> Result<(), String> {
    match element {
        Element::Repeat {
            element: child,
            max: None,
            terminators,
            ..
        } => {
            let child = simple_group_element(child.as_ref()).unwrap_or(child.as_ref());
            output.push_str(&format!("{}let mut {} = Vec::new();\n", indent, variable));
            output.push_str(&format!(
                "{}loop {{\n{}    let item_start = self.position;\n",
                indent, indent
            ));
            emit_repeat_terminator_guard(output, terminators, &format!("{}    ", indent));
            output.push_str(&format!(
                "{}    let item = match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{\n",
                indent,
                emit_element_parse(child)?
            ));
            output.push_str(&format!("{}        Ok(item) => item,\n{}        Err(_) => {{ self.position = item_start; break; }}\n{}    }};\n", indent, indent, indent));
            output.push_str(&format!(
                "{}    if self.position == item_start {{ break; }}\n{}    {}.push(item);\n{} }}\n",
                indent, indent, variable, indent
            ));
            return Ok(());
        }
        Element::Repeat {
            element: child,
            max: Some(1),
            ..
        } => {
            let child = simple_group_element(child.as_ref()).unwrap_or(child.as_ref());
            output.push_str(&format!(
                "{}let {} = {{\n{}    let optional_start = self.position;\n",
                indent, variable, indent
            ));
            output.push_str(&format!(
                "{}    match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{\n",
                indent,
                emit_element_parse(child)?
            ));
            output.push_str(&format!("{}        Ok(value) => Some(value),\n{}        Err(_) => {{ self.position = optional_start; None }}\n{}    }}\n{} }};\n", indent, indent, indent, indent));
            return Ok(());
        }
        Element::Repeat { .. } => {
            return Err("parser emitter only supports optional and zero-or-more repetitions".into())
        }
        Element::Group {
            label: Some(_),
            alternatives,
            ..
        } => {
            if alternatives.len() == 1 && alternatives[0].len() == 1 {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_element_parse(&alternatives[0][0])?
                ));
                return Ok(());
            }
            if alternatives.len() == 1 && alternatives[0].len() > 1 {
                let values = alternatives[0]
                    .iter()
                    .map(emit_element_parse)
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", ");
                output.push_str(&format!(
                    "{}let {} = {{ let group_attempt: Result<_, ParseError> = (|| {{ Ok(({})) }})(); match group_attempt {{ Ok(value) => value, Err(error) => return Err(error) }} }};\n",
                    indent, variable, values
                ));
                return Ok(());
            }
            output.push_str(&format!("{}let {} = {} ;\n", indent, variable, emit_group_expression(element)?));
            return Ok(());
        }
        Element::Group { alternatives, .. } => {
            if alternatives
                .iter()
                .any(|alternative| alternative.len() != 1)
            {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_group_expression(element)?
                ));
                return Ok(());
            }
            let first = alternatives
                .iter()
                .find_map(|alternative| alternative.first());
            if first.is_none() {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_group_expression(element)?
                ));
                return Ok(());
            }
            let first = first.expect("checked above");
            let expected_type = rust_type(first);
            if alternatives.iter().any(|alternative| {
                alternative
                    .first()
                    .map_or(true, |element| rust_type(element) != expected_type)
            }) {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_group_expression(element)?
                ));
                return Ok(());
            }
            output.push_str(&format!(
                "{}let {} = {{\n{}    let group_result: Result<_, ParseError> = (|| {{\n",
                indent, variable, indent
            ));
            for alternative in alternatives {
                let child = &alternative[0];
                output.push_str(&format!(
                    "{}        let group_start = self.position;\n",
                    indent
                ));
                output.push_str(&format!(
                    "{}        let group_attempt = (|| -> Result<_, ParseError> {{ Ok({}) }})();\n",
                    indent,
                    emit_element_parse(child)?
                ));
                output.push_str(&format!("{}        match group_attempt {{ Ok(value) => return Ok(value), Err(_) => self.position = group_start }}\n", indent));
            }
            output.push_str(&format!("{}        Err(ParseError {{ message: \"no grouped alternative\".into(), position: self.position }})\n{}    }})();\n{}    match group_result {{ Ok(value) => value, Err(error) => return Err(error) }}\n{} }};\n", indent, indent, indent, indent));
            return Ok(());
        }
        _ => {
            output.push_str(&format!(
                "{}let {} = {};\n",
                indent,
                variable,
                emit_element_parse(element)?
            ));
            return Ok(());
        }
    }
}

fn simple_group_element(element: &Element) -> Option<&Element> {
    match element {
        Element::Group { alternatives, .. }
            if alternatives.len() == 1 && alternatives[0].len() == 1 =>
        {
            Some(&alternatives[0][0])
        }
        _ => Some(element),
    }
}

fn emit_group_expression(element: &Element) -> Result<String, String> {
    let Element::Group { alternatives, .. } = element else {
        return Err("expected grouped element".into());
    };
    if alternatives.is_empty() {
        return Err("empty group".into());
    }
    let mut output = String::from("{ let group_result: Result<(), ParseError> = (|| { ");
    for alternative in alternatives {
        output.push_str("let group_start = self.position; ");
        output.push_str("let group_attempt = (|| -> Result<(), ParseError> { ");
        for child in alternative {
            output.push_str(&format!("let _ = {}; ", emit_element_parse(child)?));
        }
        output.push_str("Ok(()) })(); ");
        output.push_str("match group_attempt { Ok(value) => return Ok(value), Err(_) => self.position = group_start } ");
    }
    output.push_str("Err(ParseError { message: \"no grouped alternative\".into(), position: self.position }) })(); match group_result { Ok(value) => value, Err(error) => return Err(error) } }");
    Ok(output)
}

fn emit_group_value_expression(element: &Element) -> Result<String, String> {
    let Element::Group { alternatives, .. } = element else {
        return Err("expected grouped element".into());
    };
    if alternatives.len() != 1 || alternatives[0].len() < 2 {
        return emit_group_expression(element);
    }
    let values = alternatives[0]
        .iter()
        .map(emit_element_parse)
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    Ok(format!(
        "{{ let group_attempt: Result<_, ParseError> = (|| {{ Ok(({})) }})(); match group_attempt {{ Ok(value) => value, Err(error) => return Err(error) }} }}",
        values
    ))
}

fn emit_element_expression(element: &Element) -> Result<String, String> {
    match element {
        Element::Group { alternatives, .. } if alternatives.len() == 1 && alternatives[0].len() > 1 => {
            emit_group_value_expression(element)
        }
        Element::Group { .. } => emit_group_expression(element),
        Element::Repeat {
            element: child,
            max: None,
            terminators,
            ..
        } => {
            let mut output = String::from("{ let mut values = Vec::new(); loop { let item_start = self.position; ");
            if terminators.iter().any(|terminator| terminator == "\n") {
                output.push_str("if self.source[self.position..].starts_with('\\n') { break; } ");
            }
            let literals = terminators
                .iter()
                .filter(|terminator| terminator.as_str() != "\n")
                .map(|terminator| format!("{:?}", terminator))
                .collect::<Vec<_>>();
            if !literals.is_empty() {
                output.push_str("self.skip_trivia(); if [");
                output.push_str(&literals.join(", "));
                output.push_str(
                    "].iter().any(|literal| self.matches_terminator(literal)) { break; } ",
                );
            }
            output.push_str(&format!("let item = match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{ ", emit_element_expression(child)?));
            output.push_str("Ok(item) => item, Err(_) => { self.position = item_start; break; } }; ");
            output.push_str("if self.position == item_start { break; } values.push(item); } values }");
            Ok(output)
        }
        Element::Repeat { element: child, max: Some(1), .. } => Ok(format!(
            "{{ let optional_start = self.position; match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{ Ok(value) => Some(value), Err(_) => {{ self.position = optional_start; None }} }} }}",
            emit_element_expression(child)?
        )),
        Element::Repeat { .. } => Err("parser emitter only supports optional and zero-or-more repetitions".into()),
        Element::Literal { value, .. } => Ok(format!("self.expect_literal({:?})?", value)),
        Element::Token { token, .. } => Ok(format!("self.expect_terminal({:?})?", token)),
        Element::Rule { rule, .. } => Ok(format!("Box::new(self.parse_{}()?)", rule)),
    }
}

fn emit_repeat_terminator_guard(output: &mut String, terminators: &[String], indent: &str) {
    if terminators.is_empty() {
        return;
    }
    if terminators.iter().any(|terminator| terminator == "\n") {
        output.push_str(&format!(
            "{}if self.source[self.position..].starts_with('\\n') {{ break; }}\n",
            indent
        ));
    }
    let literals = terminators
        .iter()
        .filter(|terminator| terminator.as_str() != "\n")
        .map(|terminator| format!("{:?}", terminator))
        .collect::<Vec<_>>();
    if !literals.is_empty() {
        output.push_str(&format!(
            "{}self.skip_trivia();\n{}if [{}].iter().any(|literal| self.matches_terminator(literal)) {{ break; }}\n",
            indent,
            indent,
            literals.join(", ")
        ));
    }
}

fn element_variable(element: &Element, index: usize) -> String {
    let label = match element {
        Element::Rule { label, .. }
        | Element::Token { label, .. }
        | Element::Literal { label, .. } => label.as_deref(),
        Element::Group { label, .. } | Element::Repeat { label, .. } => label.as_deref(),
    };
    label.map_or_else(|| format!("_element_{}", index), field_name)
}

fn emit_constructor_fields(alternative: &rdgen_ir::Alternative) -> Result<String, String> {
    if alternative.constructor.fields.is_empty() {
        return Ok(String::new());
    }
    let mut output = String::from(" { ");
    for (index, field) in alternative.constructor.fields.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&format!(
            "{}: {}",
            field_name(&field.field),
            field_name(&field.source_label)
        ));
    }
    output.push_str(" }");
    Ok(output)
}

