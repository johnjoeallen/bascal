//! Rust backend for emitting hand-written-style recursive-descent parsers.

use rdgen_ir::{Element, Grammar, RecoveryStrategy, Rule};

/// Emit the typed AST declarations for a resolved grammar.
///
/// Parser-method emission is intentionally separate: the AST declaration
/// contract must remain usable by every parser backend and can be tested
/// independently of parsing control flow.
pub fn emit_ast(grammar: &Grammar) -> Result<String, String> {
    let mut output = String::from(
        "// ============================================================================\n"
            .to_owned()
            + "// DO NOT EDIT: this file is generated by rdgen.\n"
            + "// Regenerate it from the grammar source instead.\n"
            + "// ============================================================================\n\n",
    );
    output.push_str("#[derive(Clone, Debug, PartialEq)]\n");
    output.push_str("pub struct Token(pub String);\n\n");
    output.push_str("#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n");
    output.push_str("pub struct SourceSpan { pub start: usize, pub end: usize }\n\n");
    output.push_str("#[derive(Clone, Debug, PartialEq)]\n");
    output.push_str("pub struct Spanned<T> { pub span: SourceSpan, pub value: T }\n\n");
    let output_types = grammar
        .rules
        .iter()
        .map(|rule| (rule.name.clone(), type_name(&rule.output.0)))
        .collect::<std::collections::HashMap<_, _>>();
    let mut output_groups: Vec<(String, Vec<&Rule>)> = Vec::new();
    for rule in &grammar.rules {
        if let Some((_, rules)) = output_groups
            .iter_mut()
            .find(|(output, _)| output == &rule.output.0)
        {
            rules.push(rule);
        } else {
            output_groups.push((rule.output.0.clone(), vec![rule]));
        }
    }
    for (output_name, rules) in output_groups {
        let mut merged = rules[0].clone();
        if rules.len() > 1 {
            if rules.iter().any(|rule| {
                rule.alternatives
                    .iter()
                    .any(|alternative| is_default_constructor(rule, alternative))
            }) {
                return Err(format!(
                    "shared output type '{}' requires explicit constructors on every alternative",
                    output_name
                ));
            }
            merged.alternatives = rules
                .iter()
                .flat_map(|rule| rule.alternatives.iter().cloned())
                .collect();
        }
        validate_labeled_groups(
            &merged
                .alternatives
                .iter()
                .flat_map(|alternative| alternative.elements.iter())
                .collect::<Vec<_>>(),
        )?;
        emit_rule(
            &mut output,
            &merged,
            grammar
                .precedence
                .iter()
                .filter(|table| rules.iter().any(|rule| table.rule == rule.name))
                .collect(),
            &output_types,
        )?;
    }
    Ok(output)
}

fn validate_labeled_groups(elements: &[&Element]) -> Result<(), String> {
    for element in elements {
        match element {
            Element::Group {
                label: Some(label),
                alternatives,
                ..
            } if alternatives.len() > 1 => {
                return Err(format!(
                    "Rust emitter does not yet support labeled group '{}' with alternatives",
                    label
                ));
            }
            Element::Group { alternatives, .. } => {
                for alternative in alternatives {
                    validate_labeled_groups(&alternative.iter().collect::<Vec<_>>())?;
                }
            }
            Element::Repeat { element, .. } => {
                validate_labeled_groups(&[element.as_ref()])?;
            }
            Element::SameLine { element, .. } => {
                validate_labeled_groups(&[element.as_ref()])?;
            }
            _ => {}
        }
    }
    Ok(())
}

fn emit_rule(
    output: &mut String,
    rule: &Rule,
    precedence: Vec<&rdgen_ir::PrecedenceTable>,
    output_types: &std::collections::HashMap<String, String>,
) -> Result<(), String> {
    let enum_name = type_name(&rule.output.0);
    output.push_str("#[derive(Clone, Debug, PartialEq)]\n");
    output.push_str(&format!("pub enum {} {{\n", enum_name));
    let mut variants = std::collections::HashSet::new();
    let mut spanned_variants: Vec<String> = Vec::new();
    let mut precedence_variants: std::collections::HashMap<String, Vec<rdgen_ir::FieldBinding>> =
        std::collections::HashMap::new();
    for (index, alternative) in rule.alternatives.iter().enumerate() {
        if is_identity_constructor(alternative) {
            continue;
        }
        let variant = variant_name(rule, alternative, index);
        if !variants.insert(variant.clone()) {
            if rule.lexical && is_default_constructor(rule, alternative) {
                continue;
            }
            return Err(format!(
                "duplicate AST variant '{}' in rule '{}'",
                variant, rule.name
            ));
        }
        output.push_str("    ");
        output.push_str(&variant);
        if rule.lexical && is_default_constructor(rule, alternative) {
            output.push_str(" {\n        text: Token,\n        span: SourceSpan,\n    },\n");
            spanned_variants.push(variant);
            continue;
        }
        // Every constructed node (anything reaching this point is neither
        // Identity-forwarded nor a lexical default token) carries its own
        // span, even when it has no other fields.
        output.push_str(" {\n");
        let mut field_names = std::collections::HashSet::new();
        for field in &alternative.constructor.fields {
            // A fold step's magic `base`-role field is filled in externally
            // by the fold loop, not by any of this alternative's own
            // elements, so it has no labeled element to look up: its type
            // is simply this rule's own (shared) output type. A constant
            // field isn't sourced from any element either: it's a fixed
            // integer the grammar author wrote directly in the constructor.
            let field_type = if field.constant.is_some() {
                "i64".to_owned()
            } else {
                let element = find_labeled_element(&alternative.elements, &field.source_label);
                match element {
                    Some(element) => rust_type(element, output_types),
                    None if field.source_label == "base" => {
                        format!("Option<Box<{}>>", type_name(&rule.output.0))
                    }
                    None => {
                        return Err(format!(
                            "missing label '{}' in rule '{}'",
                            field.source_label, rule.name
                        ))
                    }
                }
            };
            let generated_name = field_name(&field.field);
            if !field_names.insert(generated_name.clone()) {
                return Err(format!(
                    "constructor fields '{}' collide after Rust escaping in rule '{}'",
                    field.field, rule.name
                ));
            }
            output.push_str(&format!("        {}: {},\n", generated_name, field_type));
        }
        if !field_names.insert("span".to_owned()) {
            return Err(format!(
                "constructor field 'span' is reserved for the generated node span in rule '{}'",
                rule.name
            ));
        }
        output.push_str("        span: SourceSpan,\n    },\n");
        spanned_variants.push(variant);
    }
    for table in precedence {
        for level in &table.levels {
            let Some(constructor) = &level.constructor else {
                continue;
            };
            let variant = type_name(&constructor.type_name.0);
            if !variants.insert(variant.clone()) {
                if precedence_variants
                    .get(&variant)
                    .is_some_and(|fields| same_constructor_fields(fields, &constructor.fields))
                {
                    continue;
                }
                return Err(format!(
                    "duplicate AST variant '{}' in rule '{}', including precedence constructors",
                    variant, rule.name
                ));
            }
            precedence_variants.insert(variant.clone(), constructor.fields.clone());
            output.push_str(&format!("    {} {{\n", variant));
            let mut field_names = std::collections::HashSet::new();
            for field in &constructor.fields {
                let generated_name = field_name(&field.field);
                if !field_names.insert(generated_name.clone()) {
                    return Err(format!(
                        "precedence constructor fields '{}' collide after Rust escaping in rule '{}'",
                        field.field, rule.name
                    ));
                }
                let field_type = match field.source_label.as_str() {
                    "left" | "right" => format!("Box<{}>", type_name(&rule.output.0)),
                    "operator" => "Token".to_owned(),
                    _ => unreachable!("precedence constructor validation guarantees roles"),
                };
                output.push_str(&format!("        {}: {},\n", generated_name, field_type));
            }
            output.push_str("        span: SourceSpan,\n    },\n");
            spanned_variants.push(variant);
        }
        for prefix in &table.prefix_operators {
            let Some(constructor) = &prefix.constructor else {
                continue;
            };
            let variant = type_name(&constructor.type_name.0);
            if !variants.insert(variant.clone()) {
                if precedence_variants
                    .get(&variant)
                    .is_some_and(|fields| same_constructor_fields(fields, &constructor.fields))
                {
                    continue;
                }
                return Err(format!(
                    "duplicate AST variant '{}' in rule '{}', including precedence constructors",
                    variant, rule.name
                ));
            }
            precedence_variants.insert(variant.clone(), constructor.fields.clone());
            output.push_str(&format!("    {} {{\n", variant));
            let mut field_names = std::collections::HashSet::new();
            for field in &constructor.fields {
                let generated_name = field_name(&field.field);
                if !field_names.insert(generated_name.clone()) {
                    return Err(format!(
                        "prefix constructor fields '{}' collide after Rust escaping in rule '{}'",
                        field.field, rule.name
                    ));
                }
                let field_type = match field.source_label.as_str() {
                    "operand" => format!("Box<{}>", type_name(&rule.output.0)),
                    "operator" => "Token".to_owned(),
                    _ => unreachable!("prefix constructor validation guarantees roles"),
                };
                output.push_str(&format!("        {}: {},\n", generated_name, field_type));
            }
            output.push_str("        span: SourceSpan,\n    },\n");
            spanned_variants.push(variant);
        }
    }
    output.push_str("}\n\n");
    output.push_str(&format!("impl {} {{\n", enum_name));
    output.push_str("    pub fn span(&self) -> SourceSpan {\n        match self {\n");
    for variant in &spanned_variants {
        output.push_str(&format!(
            "            {}::{} {{ span, .. }} => *span,\n",
            enum_name, variant
        ));
    }
    output.push_str("        }\n    }\n}\n\n");
    Ok(())
}

fn variant_name(rule: &Rule, alternative: &rdgen_ir::Alternative, index: usize) -> String {
    if rule.lexical && is_default_constructor(rule, alternative) {
        "Token".to_owned()
    } else if is_default_constructor(rule, alternative) {
        format!("Alt{}", index + 1)
    } else {
        type_name(&alternative.constructor.type_name.0)
    }
}

fn is_default_constructor(rule: &Rule, alternative: &rdgen_ir::Alternative) -> bool {
    alternative.constructor.fields.is_empty() && alternative.constructor.type_name.0 == rule.name
}

fn is_identity_constructor(alternative: &rdgen_ir::Alternative) -> bool {
    alternative.constructor.type_name.0 == "Identity" && alternative.constructor.fields.len() == 1
}

fn same_constructor_fields(
    left: &[rdgen_ir::FieldBinding],
    right: &[rdgen_ir::FieldBinding],
) -> bool {
    left.len() == right.len()
        && left.iter().zip(right).all(|(left, right)| {
            left.field == right.field && left.source_label == right.source_label
        })
}

fn find_labeled_element<'a>(elements: &'a [Element], label: &str) -> Option<&'a Element> {
    for element in elements {
        match element {
            Element::Rule {
                label: Some(name), ..
            }
            | Element::Token {
                label: Some(name), ..
            }
            | Element::Literal {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Group {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Repeat {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Climb {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Fold {
                label: Some(name), ..
            } if name == label => return Some(element),
            Element::Group { alternatives, .. } => {
                for alternative in alternatives {
                    if let Some(found) = find_labeled_element(alternative, label) {
                        return Some(found);
                    }
                }
            }
            Element::Repeat { element, .. } => {
                if let Some(found) =
                    find_labeled_element(std::slice::from_ref(element.as_ref()), label)
                {
                    return Some(found);
                }
            }
            Element::SameLine { element, .. } => {
                if let Some(found) =
                    find_labeled_element(std::slice::from_ref(element.as_ref()), label)
                {
                    return Some(found);
                }
            }
            _ => {}
        }
    }
    None
}

fn rust_type(
    element: &Element,
    output_types: &std::collections::HashMap<String, String>,
) -> String {
    match element {
        Element::Rule { rule, .. } => format!(
            "Box<{}>",
            output_types
                .get(rule)
                .cloned()
                .unwrap_or_else(|| type_name(rule))
        ),
        Element::Token { .. } | Element::Literal { .. } => "Token".into(),
        Element::Repeat {
            element,
            max: Some(1),
            ..
        } => format!(
            "Option<{}>",
            rust_type(rust_repeat_child(element), output_types)
        ),
        Element::Repeat { element, .. } => {
            format!(
                "Vec<{}>",
                rust_type(rust_repeat_child(element), output_types)
            )
        }
        Element::Group { alternatives, .. } if alternatives.len() == 1 => {
            rust_group_type(&alternatives[0], output_types)
        }
        Element::Group { .. } => "()".into(),
        Element::SameLine { element, .. } => rust_type(element, output_types),
        Element::Climb { atom, .. } => format!(
            "Box<{}>",
            output_types
                .get(atom)
                .cloned()
                .unwrap_or_else(|| type_name(atom))
        ),
        Element::Fold { base, .. } => format!(
            "Box<{}>",
            output_types
                .get(base)
                .cloned()
                .unwrap_or_else(|| type_name(base))
        ),
        Element::Cut { .. } => "()".into(),
        Element::LineEnd { .. } => "()".into(),
        Element::Newline { .. } => "()".into(),
    }
}

fn rust_group_type(
    elements: &[Element],
    output_types: &std::collections::HashMap<String, String>,
) -> String {
    match elements {
        [] => "()".into(),
        [element] => rust_type(element, output_types),
        elements => format!(
            "({})",
            elements
                .iter()
                .map(|element| rust_type(element, output_types))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn rust_repeat_child(element: &Element) -> &Element {
    match element {
        Element::Group { alternatives, .. }
            if alternatives.len() == 1 && alternatives[0].len() == 1 =>
        {
            &alternatives[0][0]
        }
        _ => element,
    }
}

fn type_name(name: &str) -> String {
    let mut result = String::new();
    for part in name.split('_') {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            result.extend(first.to_uppercase());
        }
        result.extend(chars);
    }
    if result.is_empty() {
        "Anonymous".into()
    } else {
        result
    }
}

fn field_name(name: &str) -> String {
    match name {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct" | "super"
        | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await"
        | "dyn" | "abstract" | "become" | "box" | "do" | "final" | "macro" | "override"
        | "priv" | "typeof" | "unsized" | "virtual" | "yield" | "try" => {
            format!("r#{}", name)
        }
        _ => name.to_owned(),
    }
}

/// Emit a Rust parser from the resolved grammar IR.
pub fn emit(grammar: &Grammar) -> Result<String, String> {
    let mut output = emit_ast(grammar)?;
    emit_precedence_metadata(&mut output, grammar)?;
    output.push_str(&emit_parser(grammar)?);
    Ok(output)
}

fn emit_precedence_metadata(output: &mut String, grammar: &Grammar) -> Result<(), String> {
    if grammar.precedence.is_empty() {
        return Ok(());
    }
    if grammar
        .rules
        .iter()
        .any(|rule| type_name(&rule.name) == "RdgenPrecedenceLevel")
    {
        return Err(
            "Rust grammar rule name collides with generated type 'RdgenPrecedenceLevel'".to_owned(),
        );
    }
    output.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\n");
    output.push_str(
        "pub struct RdgenPrecedenceField { pub field: &'static str, pub source_label: &'static str }\n\n",
    );
    output.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\n");
    output.push_str(
        "pub struct RdgenPrecedenceLevel { pub operators: &'static [&'static str], pub right_associative: bool, pub left_binding_power: usize, pub right_binding_power: usize, pub constructor_type: Option<&'static str>, pub constructor_fields: &'static [RdgenPrecedenceField] }\n\n",
    );
    let mut constants = std::collections::HashSet::new();
    for table in &grammar.precedence {
        let constant = format!("{}_PRECEDENCE", constant_name(&table.rule));
        if !constants.insert(constant.clone()) {
            return Err(format!(
                "duplicate generated precedence constant '{}'",
                constant
            ));
        }
        output.push_str(&format!(
            "pub const {}: &[RdgenPrecedenceLevel] = &[\n",
            constant
        ));
        for level in &table.levels {
            let operators = level
                .operators
                .iter()
                .map(|operator| format!("{:?}", operator))
                .collect::<Vec<_>>()
                .join(", ");
            let (left_binding_power, right_binding_power) = table
                .binding_powers(&level.operators[0])
                .expect("precedence validation guarantees a declared operator");
            let constructor_type = level
                .constructor
                .as_ref()
                .map(|constructor| constructor.type_name.0.as_str());
            let constructor_fields = level
                .constructor
                .as_ref()
                .map(|constructor| {
                    constructor
                        .fields
                        .iter()
                        .map(|field| {
                            format!(
                                "RdgenPrecedenceField {{ field: {:?}, source_label: {:?} }}",
                                field.field, field.source_label
                            )
                        })
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .filter(|fields| !fields.is_empty())
                .map_or_else(|| "&[]".to_owned(), |fields| format!("&[{}]", fields));
            output.push_str(&format!(
                "    RdgenPrecedenceLevel {{ operators: &[{}], right_associative: {}, left_binding_power: {}, right_binding_power: {}, constructor_type: {:?}, constructor_fields: {} }},\n",
                operators,
                matches!(level.associativity, rdgen_ir::Associativity::Right),
                left_binding_power,
                right_binding_power,
                constructor_type,
                constructor_fields
            ));
        }
        output.push_str("];\n");
        output.push_str(&format!(
            "pub fn {}_precedence(operator: &str) -> Option<(usize, bool)> {{ {}.iter().enumerate().find_map(|(level, spec)| spec.operators.iter().any(|candidate| *candidate == operator).then_some((level, spec.right_associative))) }}\n\n",
            table.rule, constant
        ));
        output.push_str(&format!(
            "pub fn {}_binding_power(operator: &str) -> Option<(usize, usize)> {{ {}_PRECEDENCE.iter().find_map(|spec| spec.operators.iter().any(|candidate| *candidate == operator).then_some((spec.left_binding_power, spec.right_binding_power))) }}\n\n",
            table.rule, constant_name(&table.rule)
        ));
    }
    Ok(())
}

fn constant_name(name: &str) -> String {
    name.chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

/// Emit parser control flow for the currently supported core element set.
pub fn emit_parser(grammar: &Grammar) -> Result<String, String> {
    let output_types = grammar
        .rules
        .iter()
        .map(|rule| (rule.name.clone(), type_name(&rule.output.0)))
        .collect::<std::collections::HashMap<_, _>>();
    for rule in &grammar.rules {
        for alternative in &rule.alternatives {
            if let Some(recovery) = &alternative.recovery {
                if !matches!(recovery.strategy, RecoveryStrategy::SkipUntilSync) {
                    return Err(format!(
                        "Rust parser emitter does not yet support {:?} recovery in rule '{}'",
                        recovery.strategy, rule.name
                    ));
                }
            }
        }
    }
    let start = grammar
        .rules
        .iter()
        .find(|rule| rule.name == grammar.start)
        .ok_or_else(|| format!("start rule '{}' is not declared", grammar.start))?;
    let mut output = String::from(
        "#[derive(Clone, Debug, PartialEq)]\n"
            .to_owned() + "pub struct ParseError { pub message: String, pub position: usize }\n\n"
            + "pub type TerminalScanner = fn(&str, usize, &str) -> Option<(Token, usize)>;\n\n"
            + "fn missing_terminal(_: &str, _: usize, _: &str) -> Option<(Token, usize)> { None }\n\n"
            + "pub type TriviaSkipper = fn(&str, usize) -> usize;\n\n"
            + "fn skip_no_trivia(_: &str, position: usize) -> usize { position }\n\n"
            + "pub type LiteralMatcher = fn(&str, usize, &str) -> Option<usize>;\n\n"
            + "fn match_literal(source: &str, position: usize, literal: &str) -> Option<usize> { source.get(position..)?.starts_with(literal).then_some(position + literal.len()) }\n\n"
            + "#[allow(dead_code)]\n"
            + "pub struct Parser<'a> { source: &'a str, position: usize, scan_terminal: TerminalScanner, skip_trivia: TriviaSkipper, match_literal: LiteralMatcher, best_error: Option<ParseError>, lexical_mode: bool, same_line_limit: Option<usize>, committed: bool }\n\n"
            + "#[allow(dead_code)]\n"
            + "impl<'a> Parser<'a> {\n"
            + "    pub fn new(source: &'a str) -> Self { Self::with_terminal_scanner(source, missing_terminal) }\n"
            + "    pub fn with_terminal_scanner(source: &'a str, scan_terminal: TerminalScanner) -> Self { Self::with_scanner_and_trivia(source, scan_terminal, skip_no_trivia) }\n"
            + "    pub fn with_scanner_and_trivia(source: &'a str, scan_terminal: TerminalScanner, skip_trivia: TriviaSkipper) -> Self { Self::with_lexical_config(source, scan_terminal, skip_trivia, match_literal) }\n"
            + "    pub fn with_lexical_config(source: &'a str, scan_terminal: TerminalScanner, skip_trivia: TriviaSkipper, match_literal: LiteralMatcher) -> Self { Self { source, position: 0, scan_terminal, skip_trivia, match_literal, best_error: None, lexical_mode: false, same_line_limit: None, committed: false } }\n"
            + "    pub fn source_span(&self, start: usize, end: usize) -> Option<SourceSpan> { (start <= end && end <= self.source.len() && self.source.is_char_boundary(start) && self.source.is_char_boundary(end)).then_some(SourceSpan { start, end }) }\n"
            + "    pub fn parse(&mut self) -> Result<" + &type_name(&start.output.0) + ", ParseError> { let value = match self.parse_" + &start.name + "() { Ok(value) => value, Err(error) => return Err(self.best_error.take().unwrap_or(error)) }; self.skip_trivia(); if self.position != self.source.len() { let error = ParseError { message: \"unexpected trailing input\".into(), position: self.position }; self.remember_error(&error); return Err(self.best_error.take().unwrap_or(error)); } Ok(value) }\n"
            + "    fn remember_error(&mut self, error: &ParseError) { if self.best_error.as_ref().map_or(true, |best| error.position >= best.position) { self.best_error = Some(error.clone()); } }\n"
            + "    fn skip_trivia(&mut self) { if self.lexical_mode { return; } let next = (self.skip_trivia)(self.source, self.position); let next = self.same_line_limit.map_or(next, |limit| next.min(limit)); if next >= self.position && next <= self.source.len() && self.source.is_char_boundary(next) { self.position = next; } }\n"
            + "    fn expect_line_end(&mut self) -> Result<(), ParseError> { while self.position < self.source.len() && matches!(self.source.as_bytes()[self.position], b' ' | b'\\t' | b'\\r') && self.same_line_limit.map_or(true, |limit| self.position < limit) { self.position += 1; } if self.same_line_limit.is_some_and(|limit| limit < self.source.len() && self.position >= limit) { let error = ParseError { message: \"expected same-line statement terminator\".into(), position: self.position }; self.remember_error(&error); return Err(error); } if self.position == self.source.len() { return Ok(()); } if self.source[self.position..].starts_with(':') { self.position += 1; return Ok(()); } if self.source[self.position..].starts_with('\\n') { self.position += 1; while self.position < self.source.len() && self.source[self.position..].starts_with('\\n') { self.position += 1; } return Ok(()); } let error = ParseError { message: \"expected statement terminator\".into(), position: self.position }; self.remember_error(&error); Err(error) }\n"
            + "    fn expect_newline(&mut self) -> Result<(), ParseError> { while self.source[self.position..].starts_with([' ', '\\t']) { self.position += 1; } if self.source[self.position..].starts_with(\"\\r\\n\") { self.position += 2; } else if self.source[self.position..].starts_with('\\n') { self.position += 1; } else { let error = ParseError { message: \"expected newline\".into(), position: self.position }; self.remember_error(&error); return Err(error); } while self.position < self.source.len() { if self.source[self.position..].starts_with(\"\\r\\n\") { self.position += 2; } else if self.source[self.position..].starts_with('\\n') { self.position += 1; } else { break; } } Ok(()) }\n"
            + "    fn has_terminator_boundary(&self, literal: &str, end: usize) -> bool { !literal.bytes().all(|byte| byte.is_ascii_alphabetic()) || self.source.get(end..).and_then(|rest| rest.chars().next()).map_or(true, |character| !(character.is_ascii_alphanumeric() || matches!(character, '_' | '.' | '$' | '%' | '!' | '#' | '&'))) }\n"
            + "    fn has_literal_boundary(&self, literal: &str, end: usize) -> bool { literal.len() <= 1 || !literal.bytes().all(|byte| byte.is_ascii_alphabetic()) || self.has_terminator_boundary(literal, end) }\n"
            + "    fn matches_terminator(&mut self, literal: &str) -> bool { let start = self.position; let mut first = true; for part in literal.split_whitespace() { if !first { self.skip_trivia(); } let Some(end) = (self.match_literal)(self.source, self.position, part) else { self.position = start; return false; }; if !self.has_terminator_boundary(part, end) { self.position = start; return false; } self.position = end; first = false; } self.position = start; true }\n"
            + "    fn skip_until_sync(&mut self, sync: &[&str]) { while self.position < self.source.len() { if sync.iter().any(|literal| self.source[self.position..].starts_with(literal)) { return; } if let Some(character) = self.source[self.position..].chars().next() { self.position += character.len_utf8(); } else { return; } } }\n"
            + "    fn expect_literal(&mut self, literal: &str) -> Result<Token, ParseError> {\n"
            + "        self.skip_trivia();\n"
            + "        if self.position <= self.source.len() && self.source.is_char_boundary(self.position) {\n"
            + "            if let Some(end) = (self.match_literal)(self.source, self.position, literal) {\n"
            + "                if end >= self.position && end <= self.source.len() && self.source.is_char_boundary(end) && self.has_literal_boundary(literal, end) { self.position = end; return Ok(Token(literal.to_owned())); }\n"
            + "            }\n"
            + "        }\n"
            + "        let error = ParseError { message: format!(\"expected {:?}\", literal), position: self.position }; self.remember_error(&error); Err(error)\n"
            + "    }\n"
            + "    fn expect_terminal(&mut self, name: &str) -> Result<Token, ParseError> {\n"
            + "        self.skip_trivia();\n"
            + "        match (self.scan_terminal)(self.source, self.position, name) {\n"
            + "            Some((token, end)) if end > self.position && end <= self.source.len() && self.source.is_char_boundary(self.position) && self.source.is_char_boundary(end) => { self.position = end; Ok(token) }\n"
            + "            _ => { let error = ParseError { message: format!(\"expected terminal {:?}\", name), position: self.position }; self.remember_error(&error); Err(error) },\n"
            + "        }\n"
            + "    }\n",
    );
    output.push_str(
        "    pub fn parse_precedence_climbing<T>(\n        &mut self,\n        minimum_binding_power: usize,\n        parse_atom: fn(&mut Self) -> Result<T, ParseError>,\n        parse_operator: fn(&mut Self) -> Result<Option<(Token, usize, usize)>, ParseError>,\n        combine: fn(T, Token, T) -> T,\n    ) -> Result<T, ParseError> {\n        let mut left = match parse_atom(self) {\n            Ok(value) => value,\n            Err(error) => { self.remember_error(&error); return Err(error); }\n        };\n        loop {\n            let operator_start = self.position;\n            let parsed_operator = match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            };\n            let Some((operator, left_binding_power, right_binding_power)) = parsed_operator else {\n                self.position = operator_start;\n                break;\n            };\n            if left_binding_power < minimum_binding_power {\n                self.position = operator_start;\n                break;\n            }\n            let right = match self.parse_precedence_climbing(right_binding_power, parse_atom, parse_operator, combine) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            };\n            left = combine(left, operator, right);\n        }\n        Ok(left)\n    }\n\n",
    );
    output.push_str(
        "    pub fn parse_precedence_climbing_tokens<T>(\n        &mut self,\n        minimum_binding_power: usize,\n        parse_atom: fn(&mut Self) -> Result<T, ParseError>,\n        parse_operator: fn(&mut Self) -> Result<Option<Token>, ParseError>,\n        binding_power: fn(&str) -> Option<(usize, usize)>,\n        combine: fn(T, Token, T) -> T,\n    ) -> Result<T, ParseError> {\n        let mut left = match parse_atom(self) {\n            Ok(value) => value,\n            Err(error) => { self.remember_error(&error); return Err(error); }\n        };\n        loop {\n            let operator_start = self.position;\n            let Some(operator) = match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            } else {\n                self.position = operator_start;\n                break;\n            };\n            let Some((left_binding_power, right_binding_power)) = binding_power(&operator.0) else {\n                let error = ParseError { message: format!(\"unknown precedence operator {:?}\", operator.0), position: operator_start };\n                self.remember_error(&error);\n                return Err(error);\n            };\n            if left_binding_power < minimum_binding_power {\n                self.position = operator_start;\n                break;\n            }\n            let right = match self.parse_precedence_climbing_tokens(right_binding_power, parse_atom, parse_operator, binding_power, combine) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            };\n            left = combine(left, operator, right);\n        }\n        Ok(left)\n    }\n\n",
    );
    output.push_str(
        "    /// Like `parse_precedence_climbing_tokens`, but a failed right-hand\n    /// operand backtracks the whole trailing operator instead of propagating\n    /// the error, so an operator literal that turns out to introduce\n    /// something else entirely (for example a comment marker sharing a\n    /// leading character with a binary operator) is simply left unconsumed.\n    pub fn parse_precedence_climbing_tokens_backtracking<T>(\n        &mut self,\n        minimum_binding_power: usize,\n        parse_atom: fn(&mut Self) -> Result<T, ParseError>,\n        parse_operator: fn(&mut Self) -> Result<Option<Token>, ParseError>,\n        binding_power: fn(&str) -> Option<(usize, usize)>,\n        combine: fn(T, Token, T) -> T,\n    ) -> Result<T, ParseError> {\n        let mut left = match parse_atom(self) {\n            Ok(value) => value,\n            Err(error) => { self.remember_error(&error); return Err(error); }\n        };\n        loop {\n            let operator_start = self.position;\n            let parsed_operator = match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); self.position = operator_start; break; }\n            };\n            let Some(operator) = parsed_operator else {\n                self.position = operator_start;\n                break;\n            };\n            let Some((left_binding_power, right_binding_power)) = binding_power(&operator.0) else {\n                self.position = operator_start;\n                break;\n            };\n            if left_binding_power < minimum_binding_power {\n                self.position = operator_start;\n                break;\n            }\n            let right = match self.parse_precedence_climbing_tokens_backtracking(right_binding_power, parse_atom, parse_operator, binding_power, combine) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); self.position = operator_start; break; }\n            };\n            left = combine(left, operator, right);\n        }\n        Ok(left)\n    }\n\n",
    );
    for table in &grammar.precedence {
        if grammar
            .rules
            .iter()
            .any(|rule| rule.name == format!("{}_precedence", table.rule))
        {
            return Err(format!(
                "Rust precedence wrapper for rule '{}' collides with grammar rule '{}_precedence'",
                table.rule, table.rule
            ));
        }
        output.push_str(&format!(
            "    pub fn parse_{}_precedence<T>(&mut self, minimum_binding_power: usize, parse_atom: fn(&mut Self) -> Result<T, ParseError>, parse_operator: fn(&mut Self) -> Result<Option<Token>, ParseError>, combine: fn(T, Token, T) -> T) -> Result<T, ParseError> {{ self.parse_precedence_climbing_tokens(minimum_binding_power, parse_atom, parse_operator, {}_binding_power, combine) }}\n\n",
            table.rule, table.rule
        ));
        if table.levels.iter().all(|level| level.constructor.is_some()) {
            emit_precedence_ast_helper(&mut output, table, &output_types)?;
            if let Some(atom) = climb_atom_for_table(grammar, table) {
                if grammar
                    .rules
                    .iter()
                    .any(|rule| rule.name == format!("{}_operator", table.rule))
                {
                    return Err(format!(
                        "Rust precedence wrapper for rule '{}' collides with grammar rule '{}_operator'",
                        table.rule, table.rule
                    ));
                }
                if grammar
                    .rules
                    .iter()
                    .any(|rule| rule.name == format!("{}_climb_atom", table.rule))
                {
                    return Err(format!(
                        "Rust precedence wrapper for rule '{}' collides with grammar rule '{}_climb_atom'",
                        table.rule, table.rule
                    ));
                }
                emit_precedence_climb_helpers(&mut output, table, atom, &output_types)?;
            }
        }
    }
    emit_fold_apply_base_helpers(&mut output, grammar, &output_types)?;
    for rule in &grammar.rules {
        emit_parser_rule(&mut output, rule, grammar)?;
    }
    output = output.replace(
        "let Some(operator) = match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            } else {",
        "let Some(operator) = (match parse_operator(self) {\n                Ok(value) => value,\n                Err(error) => { self.remember_error(&error); return Err(error); }\n            }) else {",
    );
    output.push_str("}\n");
    Ok(output)
}

fn emit_precedence_ast_helper(
    output: &mut String,
    table: &rdgen_ir::PrecedenceTable,
    output_types: &std::collections::HashMap<String, String>,
) -> Result<(), String> {
    let rule_type = output_types
        .get(&table.rule)
        .cloned()
        .unwrap_or_else(|| type_name(&table.rule));
    let combine_name = format!("{}_precedence_combine", table.rule);
    output.push_str(&format!(
        "    fn {}(left: {}, operator: Token, right: {}) -> {} {{\n",
        combine_name, rule_type, rule_type, rule_type
    ));
    output.push_str(
        "        let node_span = SourceSpan { start: left.span().start, end: right.span().end };\n",
    );
    output.push_str("        match operator.0.as_str() {\n");
    for level in &table.levels {
        let constructor = level
            .constructor
            .as_ref()
            .expect("precedence AST helper requires constructors for every level");
        let variant = type_name(&constructor.type_name.0);
        for operator in &level.operators {
            output.push_str(&format!(
                "            {:?} => {}::{} {{\n",
                operator, rule_type, variant
            ));
            for field in &constructor.fields {
                let value = match field.source_label.as_str() {
                    "left" => "Box::new(left)".to_owned(),
                    "operator" => "operator".to_owned(),
                    "right" => "Box::new(right)".to_owned(),
                    _ => unreachable!("precedence constructor validation guarantees roles"),
                };
                output.push_str(&format!(
                    "                {}: {},\n",
                    field_name(&field.field),
                    value
                ));
            }
            output.push_str("                span: node_span,\n            },\n");
        }
    }
    output.push_str(
        "            other => unreachable!(\"unknown precedence operator {:?}\", other),\n",
    );
    output.push_str("        }\n    }\n\n");
    output.push_str(&format!(
        "    pub fn parse_{}_precedence_ast(&mut self, minimum_binding_power: usize, parse_atom: fn(&mut Self) -> Result<{}, ParseError>, parse_operator: fn(&mut Self) -> Result<Option<Token>, ParseError>) -> Result<{}, ParseError> {{ self.parse_precedence_climbing_tokens(minimum_binding_power, parse_atom, parse_operator, {}_binding_power, {}) }}\n\n",
        table.rule, rule_type, rule_type, table.rule, format!("Self::{}", combine_name)
    ));
    Ok(())
}

/// Find the atom rule a `climb` element uses for the precedence table
/// matching `table.rule`, if any rule wires itself to that table.
fn climb_atom_for_table<'a>(
    grammar: &'a Grammar,
    table: &rdgen_ir::PrecedenceTable,
) -> Option<&'a str> {
    grammar
        .rules
        .iter()
        .find(|rule| rule.name == table.rule)
        .and_then(|rule| {
            rule.alternatives.iter().find_map(|alternative| {
                alternative
                    .elements
                    .iter()
                    .find_map(|element| match element {
                        Element::Climb { atom, .. } => Some(atom.as_str()),
                        _ => None,
                    })
            })
        })
}

/// Emit the operator matcher (and, when the table declares prefix operators,
/// the prefix-aware atom wrapper) that a `climb` element needs to drive the
/// table's precedence-climbing loop end to end.
fn emit_precedence_climb_helpers(
    output: &mut String,
    table: &rdgen_ir::PrecedenceTable,
    atom: &str,
    output_types: &std::collections::HashMap<String, String>,
) -> Result<(), String> {
    let rule_type = output_types
        .get(&table.rule)
        .cloned()
        .unwrap_or_else(|| type_name(&table.rule));

    // Longest literal first so overlapping spellings (e.g. "<" vs "<=") are
    // never mismatched by a shorter prefix.
    let mut operators: Vec<&str> = table
        .levels
        .iter()
        .flat_map(|level| level.operators.iter().map(String::as_str))
        .collect();
    operators.sort_by_key(|operator| std::cmp::Reverse(operator.len()));

    output.push_str(&format!(
        "    fn parse_{}_operator(&mut self) -> Result<Option<Token>, ParseError> {{\n        let start = self.position;\n",
        table.rule
    ));
    for operator in &operators {
        output.push_str(&format!(
            "        self.position = start;\n        if let Ok(token) = self.expect_literal({:?}) {{ return Ok(Some(token)); }}\n",
            operator
        ));
    }
    output.push_str("        self.position = start;\n        Ok(None)\n    }\n\n");

    if table.prefix_operators.is_empty() {
        return Ok(());
    }

    output.push_str(&format!(
        "    fn parse_{}_climb_atom(&mut self) -> Result<{}, ParseError> {{\n        let start = self.position;\n",
        table.rule, rule_type
    ));
    for prefix in &table.prefix_operators {
        let threshold = table
            .prefix_operand_threshold(&prefix.binds_below)
            .expect("precedence validation guarantees binds_below names a declared level");
        let Some(constructor) = &prefix.constructor else {
            continue;
        };
        let variant = type_name(&constructor.type_name.0);
        for operator in &prefix.operators {
            output.push_str(&format!(
                "        self.position = start;\n        if let Ok(operator_token) = self.expect_literal({:?}) {{\n",
                operator
            ));
            output.push_str(&format!(
                "            let operand = match self.parse_precedence_climbing_tokens_backtracking({}, Self::parse_{}_climb_atom, Self::parse_{}_operator, {}_binding_power, Self::{}_precedence_combine) {{ Ok(value) => value, Err(error) => return Err(error) }};\n",
                threshold, table.rule, table.rule, table.rule, table.rule
            ));
            output.push_str(
                "            let node_span = SourceSpan { start, end: operand.span().end };\n",
            );
            output.push_str(&format!(
                "            return Ok({}::{} {{\n",
                rule_type, variant
            ));
            for field in &constructor.fields {
                let value = match field.source_label.as_str() {
                    "operand" => "Box::new(operand)".to_owned(),
                    "operator" => "operator_token".to_owned(),
                    _ => unreachable!("prefix constructor validation guarantees roles"),
                };
                output.push_str(&format!(
                    "                {}: {},\n",
                    field_name(&field.field),
                    value
                ));
            }
            output.push_str("                span: node_span,\n            });\n        }\n");
        }
    }
    output.push_str("        self.position = start;\n");
    output.push_str(&format!("        self.parse_{}()\n    }}\n\n", atom));
    Ok(())
}

fn emit_climb_binding(
    output: &mut String,
    variable: &str,
    rule_name: &str,
    grammar: &Grammar,
    indent: &str,
) -> Result<(), String> {
    let table = grammar
        .precedence
        .iter()
        .find(|table| table.rule == rule_name)
        .ok_or_else(|| {
            format!(
                "rule '{}' uses climb but declares no precedence table",
                rule_name
            )
        })?;
    let atom_fn = if table.prefix_operators.is_empty() {
        let atom = climb_atom_for_table(grammar, table).ok_or_else(|| {
            format!(
                "climb in rule '{}' could not resolve its atom rule",
                rule_name
            )
        })?;
        format!("Self::parse_{}", atom)
    } else {
        format!("Self::parse_{}_climb_atom", rule_name)
    };
    output.push_str(&format!(
        "{}let {} = Box::new(self.parse_precedence_climbing_tokens_backtracking(0, {}, Self::parse_{}_operator, {}_binding_power, Self::{}_precedence_combine)?);\n",
        indent, variable, atom_fn, rule_name, rule_name, rule_name
    ));
    Ok(())
}

fn emit_fold_binding(output: &mut String, variable: &str, base: &str, step: &str, indent: &str) {
    output.push_str(&format!(
        "{indent}let {variable} = Box::new({{\n\
{indent}    let mut fold_accumulator = self.parse_{base}()?;\n\
{indent}    loop {{\n\
{indent}        let fold_item_start = self.position;\n\
{indent}        match self.parse_{step}() {{\n\
{indent}            Ok(step_value) => {{ fold_accumulator = Self::parse_{step}_apply_fold_base(step_value, fold_accumulator); }}\n\
{indent}            Err(_) => {{ self.position = fold_item_start; break; }}\n\
{indent}        }}\n\
{indent}    }}\n\
{indent}    fold_accumulator\n\
{indent}}});\n",
        indent = indent, variable = variable, base = base, step = step
    ));
}

/// Emit `parse_{step}_apply_fold_base`, which rebuilds a `step` rule's parsed
/// value with its magic `base`-role field replaced by the fold accumulator,
/// for every step rule any `fold` element references.
fn emit_fold_apply_base_helpers(
    output: &mut String,
    grammar: &Grammar,
    output_types: &std::collections::HashMap<String, String>,
) -> Result<(), String> {
    let mut step_names: Vec<&str> = Vec::new();
    for rule in &grammar.rules {
        for alternative in &rule.alternatives {
            for element in &alternative.elements {
                if let Element::Fold { step, .. } = element {
                    if !step_names.contains(&step.as_str()) {
                        step_names.push(step.as_str());
                    }
                }
            }
        }
    }
    for step in step_names {
        let step_rule = grammar
            .rules
            .iter()
            .find(|rule| rule.name == step)
            .ok_or_else(|| format!("fold references undefined step rule '{}'", step))?;
        if grammar
            .rules
            .iter()
            .any(|rule| rule.name == format!("{}_apply_fold_base", step))
        {
            return Err(format!(
                "Rust fold wrapper for step '{}' collides with grammar rule '{}_apply_fold_base'",
                step, step
            ));
        }
        let value_type = output_types
            .get(step)
            .cloned()
            .unwrap_or_else(|| type_name(step));
        output.push_str(&format!(
            "    fn parse_{}_apply_fold_base(value: {}, incoming_base: {}) -> {} {{\n        match value {{\n",
            step, value_type, value_type, value_type
        ));
        // `value` is typed as the whole shared output enum (it is merged
        // with every other rule sharing that `output` type), so the match
        // must be exhaustive over that enum, not just over `step`'s own
        // alternatives. Only `step`'s alternatives can ever declare a magic
        // `base`-role field (grammar validation guarantees that), so a
        // trailing wildcard safely covers every other variant unchanged.
        for (index, alternative) in step_rule.alternatives.iter().enumerate() {
            let has_base_field = alternative
                .constructor
                .fields
                .iter()
                .any(|field| field.source_label == "base");
            if !has_base_field {
                continue;
            }
            let variant = variant_name(step_rule, alternative, index);
            let pattern_fields = alternative
                .constructor
                .fields
                .iter()
                .map(|field| {
                    let name = field_name(&field.field);
                    if field.source_label == "base" {
                        format!("{}: _", name)
                    } else {
                        name
                    }
                })
                .collect::<Vec<_>>()
                .join(", ");
            let rebuild_fields = alternative
                .constructor
                .fields
                .iter()
                .map(|field| {
                    let name = field_name(&field.field);
                    if field.source_label == "base" {
                        format!("{}: Some(Box::new(incoming_base))", name)
                    } else {
                        name
                    }
                })
                .collect::<Vec<_>>()
                .join(", ");
            // `original_span` only ever covered the step's own elements
            // (e.g. just ".member"); the folded node's span must start
            // where the accumulated base started instead.
            output.push_str(&format!(
                "            {value_type}::{variant} {{ {pattern_fields}, span: original_span }} => {{\n                let node_span = SourceSpan {{ start: incoming_base.span().start, end: original_span.end }};\n                {value_type}::{variant} {{ {rebuild_fields}, span: node_span }}\n            }},\n",
                value_type = value_type, variant = variant, pattern_fields = pattern_fields, rebuild_fields = rebuild_fields
            ));
        }
        output.push_str("            other => other,\n        }\n    }\n\n");
    }
    Ok(())
}

fn emit_parser_rule(output: &mut String, rule: &Rule, grammar: &Grammar) -> Result<(), String> {
    output.push_str(&format!(
        "    fn parse_{}(&mut self) -> Result<{}, ParseError> {{\n",
        rule.name,
        type_name(&rule.output.0)
    ));
    output.push_str(
        "        let previous_commit = self.committed;\n        self.committed = false;\n",
    );
    if rule.lexical {
        output.push_str("        let lexical_start = self.position;\n        self.skip_trivia();\n        let lexical_token_start = self.position;\n        let previous_lexical_mode = self.lexical_mode;\n        self.lexical_mode = true;\n");
    }
    for (index, alternative) in rule.alternatives.iter().enumerate() {
        if !rule.lexical {
            // Prefixed to avoid colliding with a grammar field also named
            // "start" (e.g. `for_stmt`'s loop-start expression), which
            // would otherwise shadow this inside the closure below.
            //
            // Deliberately does *not* skip trivia first (unlike the
            // lexical case below): some builtin elements (`newline`,
            // `same_line`) are only meaningful because trivia is *not*
            // eagerly skipped ahead of them, so a non-lexical rule's span
            // can start slightly before its first real token when that
            // token is preceded by skippable trivia the rule itself never
            // explicitly consumes before reaching it.
            output.push_str("        let rdgen_span_start = self.position;\n");
        }
        output.push_str(&format!(
            "        let attempt: Result<{}, ParseError> = (|| {{\n",
            type_name(&rule.output.0)
        ));
        for (index, element) in alternative.elements.iter().enumerate() {
            let variable = element_variable(element, index);
            if matches!(element, Element::Climb { .. }) {
                emit_climb_binding(output, &variable, &rule.name, grammar, "            ")?;
                continue;
            }
            if let Element::Fold { base, step, .. } = element {
                emit_fold_binding(output, &variable, base, step, "            ");
                continue;
            }
            emit_element_binding(output, element, &variable, "            ")?;
        }
        let is_identity = is_identity_constructor(alternative);
        let is_lexical_default = rule.lexical && is_default_constructor(rule, alternative);
        if !is_identity && !is_lexical_default {
            // Every constructed node gets its own span; Identity forwards an
            // existing node instead of building a new one, and the lexical
            // default (raw token) case already computes its own span above.
            output.push_str("            let rdgen_span_end = self.position;\n");
        }
        let construction = if is_identity {
            format!(
                "*{}",
                field_name(&alternative.constructor.fields[0].source_label)
            )
        } else if is_lexical_default {
            format!(
                "{}::Token {{ text: Token(self.source[lexical_token_start..self.position].to_owned()), span: SourceSpan {{ start: lexical_token_start, end: self.position }} }}",
                type_name(&rule.output.0)
            )
        } else {
            let span_start = if rule.lexical {
                "lexical_token_start"
            } else {
                "rdgen_span_start"
            };
            let span_expr = format!(
                "SourceSpan {{ start: {}, end: rdgen_span_end }}",
                span_start
            );
            format!(
                "{}::{}{}",
                type_name(&rule.output.0),
                variant_name(rule, alternative, index),
                emit_constructor_fields(alternative, &span_expr)?
            )
        };
        output.push_str(&format!("            Ok({})\n", construction));
        output.push_str("        })();\n");
        if rule.lexical {
            output.push_str("        match attempt { Ok(value) => { self.lexical_mode = previous_lexical_mode; self.committed = previous_commit; return Ok(value); }, Err(error) => { if self.committed { self.lexical_mode = previous_lexical_mode; return Err(error); } self.position = lexical_token_start } }\n");
        } else {
            output.push_str("        match attempt { Ok(value) => { self.committed = previous_commit; return Ok(value); }, Err(error) => { if self.committed { return Err(error); } self.position = rdgen_span_start } }\n");
        }
    }
    if rule.lexical {
        output.push_str("        self.lexical_mode = previous_lexical_mode;\n        self.position = lexical_start;\n");
    }
    output.push_str("        self.committed = previous_commit;\n");
    if let Some(recovery) = rule.alternatives.iter().find_map(|alternative| {
        (alternative
            .recovery
            .as_ref()
            .is_some_and(|point| matches!(point.strategy, RecoveryStrategy::SkipUntilSync)))
        .then(|| {
            alternative
                .recovery
                .as_ref()
                .expect("recovery point checked")
        })
    }) {
        let sync = recovery
            .sync_tokens
            .iter()
            .map(|token| format!("{:?}", token))
            .collect::<Vec<_>>()
            .join(", ");
        output.push_str(&format!("        self.skip_until_sync(&[{}]);\n", sync));
    }
    output.push_str(&format!("        let error = ParseError {{ message: \"no alternative for {}\".into(), position: self.position }}; self.remember_error(&error); Err(error)\n", rule.name));
    output.push_str("    }\n");
    Ok(())
}

fn emit_element_parse(element: &Element) -> Result<String, String> {
    match element {
        Element::Literal { value, .. } => Ok(format!("self.expect_literal({:?})?", value)),
        Element::Token { token, .. } => Ok(format!("self.expect_terminal({:?})?", token)),
        Element::Rule { rule, .. } => Ok(format!("Box::new(self.parse_{}()?)", rule)),
        Element::SameLine { .. } => Ok(format!("({})?", emit_element_expression(element)?)),
        Element::Cut { .. } => Ok("{ self.committed = true; () }".into()),
        Element::LineEnd { .. } => Ok("self.expect_line_end()?".into()),
        Element::Newline { .. } => Ok("self.expect_newline()?".into()),
        Element::Group { .. } | Element::Repeat { .. } => emit_element_expression(element),
        Element::Climb { .. } => {
            Err("climb elements may not be nested inside groups or repetitions".into())
        }
        Element::Fold { .. } => {
            Err("fold elements may not be nested inside groups or repetitions".into())
        }
    }
}

fn emit_element_binding(
    output: &mut String,
    element: &Element,
    variable: &str,
    indent: &str,
) -> Result<(), String> {
    match element {
        Element::Repeat {
            element: child,
            max: None,
            terminators,
            ..
        } => {
            let child = simple_group_element(child.as_ref()).unwrap_or(child.as_ref());
            output.push_str(&format!("{}let mut {} = Vec::new();\n", indent, variable));
            output.push_str(&format!(
                "{}loop {{\n{}    let item_start = self.position;\n",
                indent, indent
            ));
            emit_repeat_terminator_guard(output, terminators, &format!("{}    ", indent));
            output.push_str(&format!(
                "{}    let item = match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{\n",
                indent,
                emit_element_parse(child)?
            ));
            output.push_str(&format!("{}        Ok(item) => item,\n{}        Err(_) => {{ self.position = item_start; break; }}\n{}    }};\n", indent, indent, indent));
            output.push_str(&format!(
                "{}    if self.position == item_start {{ break; }}\n{}    {}.push(item);\n{} }}\n",
                indent, indent, variable, indent
            ));
            return Ok(());
        }
        Element::Repeat {
            element: child,
            max: Some(1),
            ..
        } => {
            let child = simple_group_element(child.as_ref()).unwrap_or(child.as_ref());
            output.push_str(&format!(
                "{}let {} = {{\n{}    let optional_start = self.position;\n",
                indent, variable, indent
            ));
            output.push_str(&format!(
                "{}    match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{\n",
                indent,
                emit_element_parse(child)?
            ));
            output.push_str(&format!("{}        Ok(value) => Some(value),\n{}        Err(_) => {{ self.position = optional_start; None }}\n{}    }}\n{} }};\n", indent, indent, indent, indent));
            return Ok(());
        }
        Element::Repeat { .. } => {
            return Err("parser emitter only supports optional and zero-or-more repetitions".into())
        }
        Element::Group {
            label: Some(_),
            alternatives,
            ..
        } => {
            if alternatives.len() == 1 && alternatives[0].len() == 1 {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_element_parse(&alternatives[0][0])?
                ));
                return Ok(());
            }
            if alternatives.len() == 1 && alternatives[0].len() > 1 {
                let values = alternatives[0]
                    .iter()
                    .map(emit_element_parse)
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", ");
                output.push_str(&format!(
                    "{}let {} = {{ let group_attempt: Result<_, ParseError> = (|| {{ Ok(({})) }})(); match group_attempt {{ Ok(value) => value, Err(error) => return Err(error) }} }};\n",
                    indent, variable, values
                ));
                return Ok(());
            }
            output.push_str(&format!(
                "{}let {} = {} ;\n",
                indent,
                variable,
                emit_group_expression(element)?
            ));
            return Ok(());
        }
        Element::Group { alternatives, .. } => {
            if alternatives
                .iter()
                .any(|alternative| alternative.len() != 1)
            {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_group_expression(element)?
                ));
                return Ok(());
            }
            let first = alternatives
                .iter()
                .find_map(|alternative| alternative.first());
            if first.is_none() {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_group_expression(element)?
                ));
                return Ok(());
            }
            let first = first.expect("checked above");
            let output_types = std::collections::HashMap::new();
            let expected_type = rust_type(first, &output_types);
            if alternatives.iter().any(|alternative| {
                alternative.first().map_or(true, |element| {
                    rust_type(element, &output_types) != expected_type
                })
            }) {
                output.push_str(&format!(
                    "{}let {} = {};\n",
                    indent,
                    variable,
                    emit_group_expression(element)?
                ));
                return Ok(());
            }
            output.push_str(&format!(
                "{}let {} = {{\n{}    let group_result: Result<_, ParseError> = (|| {{\n",
                indent, variable, indent
            ));
            for alternative in alternatives {
                let child = &alternative[0];
                output.push_str(&format!(
                    "{}        let group_start = self.position;\n",
                    indent
                ));
                output.push_str(&format!(
                    "{}        let group_attempt = (|| -> Result<_, ParseError> {{ Ok({}) }})();\n",
                    indent,
                    emit_element_parse(child)?
                ));
                output.push_str(&format!("{}        match group_attempt {{ Ok(value) => return Ok(value), Err(_) => self.position = group_start }}\n", indent));
            }
            output.push_str(&format!("{}        Err(ParseError {{ message: \"no grouped alternative\".into(), position: self.position }})\n{}    }})();\n{}    match group_result {{ Ok(value) => value, Err(error) => return Err(error) }}\n{} }};\n", indent, indent, indent, indent));
            return Ok(());
        }
        _ => {
            output.push_str(&format!(
                "{}let {} = {};\n",
                indent,
                variable,
                emit_element_parse(element)?
            ));
            return Ok(());
        }
    }
}

fn simple_group_element(element: &Element) -> Option<&Element> {
    match element {
        Element::Group { alternatives, .. }
            if alternatives.len() == 1 && alternatives[0].len() == 1 =>
        {
            Some(&alternatives[0][0])
        }
        _ => Some(element),
    }
}

fn emit_group_expression(element: &Element) -> Result<String, String> {
    let Element::Group { alternatives, .. } = element else {
        return Err("expected grouped element".into());
    };
    if alternatives.is_empty() {
        return Err("empty group".into());
    }
    let mut output = String::from("{ let group_result: Result<(), ParseError> = (|| { ");
    for alternative in alternatives {
        output.push_str("let group_start = self.position; ");
        output.push_str("let group_attempt = (|| -> Result<(), ParseError> { ");
        for child in alternative {
            output.push_str(&format!("let _ = {}; ", emit_element_parse(child)?));
        }
        output.push_str("Ok(()) })(); ");
        output.push_str("match group_attempt { Ok(value) => return Ok(value), Err(_) => self.position = group_start } ");
    }
    output.push_str("Err(ParseError { message: \"no grouped alternative\".into(), position: self.position }) })(); match group_result { Ok(value) => value, Err(error) => return Err(error) } }");
    Ok(output)
}

fn emit_group_value_expression(element: &Element) -> Result<String, String> {
    let Element::Group { alternatives, .. } = element else {
        return Err("expected grouped element".into());
    };
    if alternatives.len() != 1 || alternatives[0].len() < 2 {
        return emit_group_expression(element);
    }
    let values = alternatives[0]
        .iter()
        .map(emit_element_parse)
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    Ok(format!(
        "{{ let group_attempt: Result<_, ParseError> = (|| {{ Ok(({})) }})(); match group_attempt {{ Ok(value) => value, Err(error) => return Err(error) }} }}",
        values
    ))
}

fn emit_element_expression(element: &Element) -> Result<String, String> {
    match element {
        Element::SameLine { element, .. } => Ok(format!(
            "{{ let same_line_start = self.position; let previous_same_line_limit = self.same_line_limit; let line_limit = self.source[same_line_start..].find('\\n').map(|offset| same_line_start + offset).unwrap_or(self.source.len()); self.same_line_limit = Some(previous_same_line_limit.map_or(line_limit, |limit| limit.min(line_limit))); let same_line_result = (|| -> Result<_, ParseError> {{ Ok({}) }})(); self.same_line_limit = previous_same_line_limit; same_line_result }}",
            emit_element_parse(element)?
        )),
        Element::Group { alternatives, .. }
            if alternatives.len() == 1 && alternatives[0].len() == 1 =>
        {
            emit_element_parse(&alternatives[0][0])
        }
        Element::Group { alternatives, .. } if alternatives.len() == 1 && alternatives[0].len() > 1 => {
            emit_group_value_expression(element)
        }
        Element::Group { .. } => emit_group_expression(element),
        Element::Repeat {
            element: child,
            max: None,
            terminators,
            ..
        } => {
            let mut output = String::from("{ let mut values = Vec::new(); loop { let item_start = self.position; ");
            if terminators.iter().any(|terminator| terminator == "\n") {
                output.push_str("if self.source[self.position..].starts_with('\\n') { break; } ");
            }
            let literals = terminators
                .iter()
                .filter(|terminator| terminator.as_str() != "\n")
                .map(|terminator| format!("{:?}", terminator))
                .collect::<Vec<_>>();
            if !literals.is_empty() {
                output.push_str("self.skip_trivia(); if [");
                output.push_str(&literals.join(", "));
                output.push_str(
                    "].iter().any(|literal| self.matches_terminator(literal)) { break; } ",
                );
            }
            output.push_str(&format!("let item = match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{ ", emit_element_expression(child)?));
            output.push_str("Ok(item) => item, Err(_) => { self.position = item_start; break; } }; ");
            output.push_str("if self.position == item_start { break; } values.push(item); } values }");
            Ok(output)
        }
        Element::Repeat { element: child, max: Some(1), .. } => Ok(format!(
            "{{ let optional_start = self.position; match (|| -> Result<_, ParseError> {{ Ok({}) }})() {{ Ok(value) => Some(value), Err(_) => {{ self.position = optional_start; None }} }} }}",
            emit_element_expression(child)?
        )),
        Element::Repeat { .. } => Err("parser emitter only supports optional and zero-or-more repetitions".into()),
        Element::Literal { value, .. } => Ok(format!("self.expect_literal({:?})?", value)),
        Element::Token { token, .. } => Ok(format!("self.expect_terminal({:?})?", token)),
        Element::Rule { rule, .. } => Ok(format!("Box::new(self.parse_{}()?)", rule)),
        Element::Cut { .. } => Ok("{ self.committed = true; () }".into()),
        Element::LineEnd { .. } => Ok("self.expect_line_end()?".into()),
        Element::Newline { .. } => Ok("self.expect_newline()?".into()),
        Element::Climb { .. } => {
            Err("climb elements may not be nested inside groups or repetitions".into())
        }
        Element::Fold { .. } => {
            Err("fold elements may not be nested inside groups or repetitions".into())
        }
    }
}

fn emit_repeat_terminator_guard(output: &mut String, terminators: &[String], indent: &str) {
    if terminators.is_empty() {
        return;
    }
    if terminators.iter().any(|terminator| terminator == "\n") {
        output.push_str(&format!(
            "{}if self.source[self.position..].starts_with('\\n') {{ break; }}\n",
            indent
        ));
    }
    let literals = terminators
        .iter()
        .filter(|terminator| terminator.as_str() != "\n")
        .map(|terminator| format!("{:?}", terminator))
        .collect::<Vec<_>>();
    if !literals.is_empty() {
        output.push_str(&format!(
            "{}self.skip_trivia();\n{}if [{}].iter().any(|literal| self.matches_terminator(literal)) {{ break; }}\n",
            indent,
            indent,
            literals.join(", ")
        ));
    }
}

fn element_variable(element: &Element, index: usize) -> String {
    let label = match element {
        Element::Rule { label, .. }
        | Element::Token { label, .. }
        | Element::Literal { label, .. } => label.as_deref(),
        Element::Group { label, .. } | Element::Repeat { label, .. } => label.as_deref(),
        Element::Climb { label, .. } | Element::Fold { label, .. } => label.as_deref(),
        Element::SameLine { .. } => None,
        Element::Cut { .. } => None,
        Element::LineEnd { .. } => None,
        Element::Newline { .. } => None,
    };
    label.map_or_else(|| format!("_element_{}", index), field_name)
}

fn emit_constructor_fields(
    alternative: &rdgen_ir::Alternative,
    span_expr: &str,
) -> Result<String, String> {
    let mut output = String::from(" { ");
    for field in &alternative.constructor.fields {
        // A fold step's magic `base`-role field isn't bound by any of this
        // alternative's own elements: it starts as `None` and is filled in
        // by the fold loop once the accumulated base is known.
        let is_magic_fold_base = field.source_label == "base"
            && find_labeled_element(&alternative.elements, &field.source_label).is_none();
        let value = if let Some(constant) = field.constant {
            constant.to_string()
        } else if is_magic_fold_base {
            "None".to_owned()
        } else {
            field_name(&field.source_label)
        };
        output.push_str(&format!("{}: {}, ", field_name(&field.field), value));
    }
    output.push_str(&format!("span: {} }}", span_expr));
    Ok(output)
}

